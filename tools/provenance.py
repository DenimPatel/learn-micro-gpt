def all_entries() -> tuple[ProvenanceEntry, ...]:
    return PROVENANCE


def main(argv: list[str] | None = None) -> int:
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify that every pinned (non-derived) file still matches its sha256",
    )
    args = parser.parse_args(argv)

    if args.check:
        from tools import check_provenance  # noqa: PLC0415

        return check_provenance.run()

    for entry in all_entries():
        print(f"{entry.sha256:<64}  {entry.path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
