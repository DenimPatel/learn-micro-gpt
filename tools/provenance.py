#!/usr/bin/env python3
"""Provenance manifest for every vendored or derived file in this repository.

This module is the single source of truth for `docs/PROVENANCE.md` and for the
sha256 check that CI runs. It is deliberately stdlib-only: the whole point of
this repository is that you should not need a package manager to audit it.

Two kinds of entry live here:

`VENDORED`
    A file whose bytes came from somewhere else. Its sha256 is pinned, and
    `make verify-provenance` fails if the bytes move without a deliberate,
    reviewable edit to this file.

`DERIVED`
    A file we produced by adapting someone else's. Its sha256 is recorded for
    the current revision but is *not* an upstream pin -- it is expected to
    change whenever we change the file. Use `derived=True` for those.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass, field
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent


@dataclass(frozen=True)
class ProvenanceEntry:
    path: str
    origin: str
    url: str
    license: str
    author: str
    note: str
    #: Literal digest. For pinned entries this is the upstream byte sequence and
    #: the check compares against it, so editing the file fails the build. For
    #: derived entries it is the digest of our current revision, refreshed with
    #: `make provenance`; it is recorded, not enforced.
    sha256: str
    derived: bool = False
    license_file: str | None = None
    aliases: tuple[str, ...] = field(default_factory=tuple)

    def actual_sha256(self) -> str | None:
        target = REPO_ROOT / self.path
        if not target.is_file():
            return None
        digest = hashlib.sha256()
        with target.open("rb") as handle:
            for chunk in iter(lambda: handle.read(1 << 20), b""):
                digest.update(chunk)
        return digest.hexdigest()


